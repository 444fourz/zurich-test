-- Underwriting database schema (SQLite).
-- Dates are stored as ISO 8601 UTC text. Foreign keys must be enabled on every
-- connection with: PRAGMA foreign_keys = ON;

-- ---------------------------------------------------------------------------
-- Users and applicants
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS users (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    email          TEXT NOT NULL UNIQUE COLLATE NOCASE,
    password_hash  TEXT NOT NULL,
    full_name      TEXT NOT NULL,
    role           TEXT NOT NULL DEFAULT 'applicant'
                   CHECK (role IN ('applicant', 'underwriter', 'administrator')),
    is_active      INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE IF NOT EXISTS applicants (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id         INTEGER NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    first_name      TEXT NOT NULL,
    last_name       TEXT NOT NULL,
    date_of_birth   TEXT NOT NULL CHECK (date_of_birth GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]'),
    email           TEXT NOT NULL COLLATE NOCASE,
    phone           TEXT NOT NULL,
    address_line1   TEXT NOT NULL,
    address_line2   TEXT,
    city            TEXT NOT NULL,
    postcode        TEXT NOT NULL,
    created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- Applications
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS applications (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    reference     TEXT NOT NULL UNIQUE,  -- human-friendly reference, generated by the app
    applicant_id  INTEGER NOT NULL REFERENCES applicants (id) ON DELETE RESTRICT,
    product       TEXT NOT NULL DEFAULT 'standard_health',
    status        TEXT NOT NULL DEFAULT 'draft'
                  CHECK (status IN (
                      'draft',
                      'submitted',
                      'auto_approved',
                      'referred',
                      'auto_declined',
                      'approved',
                      'declined',
                      'more_info_required'
                  )),
    submitted_at  TEXT,
    created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    CHECK (status = 'draft' OR submitted_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS application_lifestyle (
    application_id        INTEGER PRIMARY KEY REFERENCES applications (id) ON DELETE CASCADE,
    smoker                TEXT NOT NULL CHECK (smoker IN ('never', 'former', 'current')),
    alcohol_consumption   TEXT NOT NULL CHECK (alcohol_consumption IN ('none', 'occasional', 'moderate', 'heavy')),
    exercise_frequency    TEXT NOT NULL CHECK (exercise_frequency IN ('none', 'occasional', 'regular', 'frequent')),
    occupation            TEXT NOT NULL,
    hazardous_activities  TEXT NOT NULL CHECK (hazardous_activities IN ('none', 'some', 'high'))
);

CREATE TABLE IF NOT EXISTS application_medical (
    application_id          INTEGER PRIMARY KEY REFERENCES applications (id) ON DELETE CASCADE,
    height_cm               REAL NOT NULL CHECK (height_cm BETWEEN 100 AND 250),
    weight_kg               REAL NOT NULL CHECK (weight_kg BETWEEN 30 AND 300),
    bmi                     REAL GENERATED ALWAYS AS (
                                round(weight_kg / ((height_cm / 100.0) * (height_cm / 100.0)), 1)
                            ) VIRTUAL,
    medications             TEXT,
    family_history          TEXT NOT NULL CHECK (family_history IN ('none', 'some', 'significant')),
    recent_hospitalisation  INTEGER NOT NULL CHECK (recent_hospitalisation IN (0, 1))
);

-- Lookup of conditions offered on the form. "None" is represented by having no
-- rows in application_conditions.
CREATE TABLE IF NOT EXISTS medical_conditions (
    id    INTEGER PRIMARY KEY AUTOINCREMENT,
    code  TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS application_conditions (
    application_id  INTEGER NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    condition_id    INTEGER NOT NULL REFERENCES medical_conditions (id) ON DELETE RESTRICT,
    PRIMARY KEY (application_id, condition_id)
);

INSERT OR IGNORE INTO medical_conditions (code, label) VALUES
    ('diabetes',        'Diabetes'),
    ('hypertension',    'High blood pressure'),
    ('heart_disease',   'Heart disease'),
    ('asthma',          'Asthma'),
    ('cancer',          'Cancer (current or previous)'),
    ('mental_health',   'Mental health condition'),
    ('other_chronic',   'Other chronic condition');

-- ---------------------------------------------------------------------------
-- Assessments, decisions and documents
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS risk_assessments (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    application_id  INTEGER NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    score           INTEGER NOT NULL,
    outcome         TEXT NOT NULL CHECK (outcome IN ('auto_approve', 'refer', 'auto_decline')),
    explanation     TEXT,                 -- JSON: which rules fired
    rules_version   TEXT NOT NULL,
    created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE IF NOT EXISTS decisions (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    application_id  INTEGER NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    decided_by      INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    outcome         TEXT NOT NULL CHECK (outcome IN ('approved', 'declined', 'more_info_required')),
    reason          TEXT NOT NULL CHECK (length(trim(reason)) > 0),
    decided_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE IF NOT EXISTS documents (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    application_id  INTEGER NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    storage_key     TEXT NOT NULL UNIQUE,
    document_type   TEXT NOT NULL,
    original_name   TEXT NOT NULL,
    uploaded_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- Audit log (append-only)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS audit_log (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    actor_user_id  INTEGER REFERENCES users (id) ON DELETE SET NULL,
    action         TEXT NOT NULL,
    entity_type    TEXT NOT NULL,
    entity_id      INTEGER,
    before_json    TEXT,
    after_json     TEXT,
    created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_applications_applicant ON applications (applicant_id);
CREATE INDEX IF NOT EXISTS idx_applications_status    ON applications (status, submitted_at);
CREATE INDEX IF NOT EXISTS idx_assessments_application ON risk_assessments (application_id, created_at);
CREATE INDEX IF NOT EXISTS idx_decisions_application   ON decisions (application_id, decided_at);
CREATE INDEX IF NOT EXISTS idx_documents_application   ON documents (application_id);
CREATE INDEX IF NOT EXISTS idx_audit_entity            ON audit_log (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_actor             ON audit_log (actor_user_id, created_at);

-- ---------------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------------

CREATE TRIGGER IF NOT EXISTS trg_users_updated
AFTER UPDATE ON users
FOR EACH ROW WHEN NEW.updated_at = OLD.updated_at
BEGIN
    UPDATE users SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = NEW.id;
END;

CREATE TRIGGER IF NOT EXISTS trg_applicants_updated
AFTER UPDATE ON applicants
FOR EACH ROW WHEN NEW.updated_at = OLD.updated_at
BEGIN
    UPDATE applicants SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = NEW.id;
END;

CREATE TRIGGER IF NOT EXISTS trg_applications_updated
AFTER UPDATE ON applications
FOR EACH ROW WHEN NEW.updated_at = OLD.updated_at
BEGIN
    UPDATE applications SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = NEW.id;
END;

-- The audit log and decisions are append-only.
CREATE TRIGGER IF NOT EXISTS trg_audit_no_update
BEFORE UPDATE ON audit_log
BEGIN
    SELECT RAISE(ABORT, 'audit_log is append-only');
END;

CREATE TRIGGER IF NOT EXISTS trg_audit_no_delete
BEFORE DELETE ON audit_log
BEGIN
    SELECT RAISE(ABORT, 'audit_log is append-only');
END;

CREATE TRIGGER IF NOT EXISTS trg_decisions_no_update
BEFORE UPDATE ON decisions
BEGIN
    SELECT RAISE(ABORT, 'decisions are append-only; record a new decision instead');
END;

CREATE TRIGGER IF NOT EXISTS trg_decisions_no_delete
BEFORE DELETE ON decisions
BEGIN
    SELECT RAISE(ABORT, 'decisions are append-only; record a new decision instead');
END;
